import {chromium} from 'playwright';
import {existsSync} from 'node:fs';
const browser=await chromium.launch(existsSync('/usr/bin/chromium')?{executablePath:'/usr/bin/chromium',args:['--no-sandbox']}:{ });
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
await page.goto('http://127.0.0.1:4321/publications/');
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'docs/publication-abstracts-preview/desktop-collapsed.png'});
await page.locator('#pub-2026-01 summary').click();
await page.screenshot({path:'docs/publication-abstracts-preview/desktop-expanded.png'});
await page.locator('#pub-2026-01').screenshot({path:'docs/publication-abstracts-preview/study-summary.png'});
await page.locator('#pub-2009-19 summary').click();
await page.locator('#pub-2009-19').screenshot({path:'docs/publication-abstracts-preview/author-summary.png'});
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:4321/publications/?year=2026');
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'docs/publication-abstracts-preview/mobile-collapsed.png'});
await page.locator('#pub-2026-01 summary').click();
await page.screenshot({path:'docs/publication-abstracts-preview/mobile-expanded.png',fullPage:true});
await page.goto('http://127.0.0.1:4321/publications/?q=Sleep+paralysis');
await page.locator('#pub-2020-10 summary').click();
await page.screenshot({path:'docs/publication-abstracts-preview/mobile-search-expanded.png',fullPage:true});
await browser.close();
